SURAH_NAME = {n: name for n, name, _ in SURAHS}
AYAH_COUNT = {n: count for n, _, count in SURAHS}

# عدد الآيات التي تسبق كل سورة (للحساب المتسلسل لعدد الآيات بين نقطتين)
_OFFSET = {}
_acc = 0
for _n, _name, _count in SURAHS:
    _OFFSET[_n] = _acc
    _acc += _count
TOTAL_AYAHS = _acc


def surahs_for_js():
    """قائمة مبسّطة تُمرَّر لجافاسكربت: [{n, name, ayahs}, ...]."""
    return [{'n': n, 'name': name, 'ayahs': count} for n, name, count in SURAHS]


def valid_point(surah, ayah):
    """هل (سورة، آية) نقطة صحيحة؟"""
    return surah in AYAH_COUNT and 1 <= ayah <= AYAH_COUNT[surah]


def abs_index(surah, ayah):
    """الترتيب المتسلسل للآية في المصحف (1 … 6236)."""
    return _OFFSET[surah] + ayah


def validate_range(from_surah, from_ayah, to_surah, to_ayah):
    """يعيد نص الخطأ بالعربية، أو None إن كان النطاق صحيحاً."""
    if not valid_point(from_surah, from_ayah):
        return 'سورة أو آية البداية غير صحيحة'
    if not valid_point(to_surah, to_ayah):
        return 'سورة أو آية النهاية غير صحيحة'
    if abs_index(to_surah, to_ayah) < abs_index(from_surah, from_ayah):
        return 'نهاية المقطع قبل بدايته'
    return None


def ayah_span(from_surah, from_ayah, to_surah, to_ayah):
    """عدد الآيات في النطاق (شاملاً الطرفين)."""
    return abs_index(to_surah, to_ayah) - abs_index(from_surah, from_ayah) + 1


def safe_ayah_span(from_surah, from_ayah, to_surah, to_ayah):
    """مثل ayah_span لكن يعيد 0 بدل رفع خطأ إن كانت القيم المخزّنة غير صحيحة (كتعديل يدوي في قاعدة البيانات)."""
    try:
        if validate_range(from_surah, from_ayah, to_surah, to_ayah):
            return 0
        return ayah_span(from_surah, from_ayah, to_surah, to_ayah)
    except Exception:
        return 0


def format_range(from_surah, from_ayah, to_surah, to_ayah):
    """
    صيغة مقروءة للمقطع المُسمَّع:
      نفس السورة:   «البقرة (1–25)» / «البقرة (255)» / «الملك (كاملة)»
      عدة سور:      «النبأ (1) ← النازعات (46)»
    """
    a, b = SURAH_NAME.get(from_surah, '؟'), SURAH_NAME.get(to_surah, '؟')
    if from_surah == to_surah:
        if from_ayah == to_ayah:
            return f'{a} ({from_ayah})'
        if from_ayah == 1 and to_ayah == AYAH_COUNT.get(from_surah):
            return f'{a} (كاملة)'
        return f'{a} ({from_ayah}–{to_ayah})'
    return f'{a} ({from_ayah}) ← {b} ({to_ayah})'
